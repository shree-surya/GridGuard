"""Converts a TTF into an Adafruit GFX font (1-bit, ASCII 0x20-0x7E), rendered by FreeType without
anti-aliasing so small sizes stay crisp. Usage: ttf2gfx.py out.h name:file.ttf:px [...]"""
import sys
from PIL import Image, ImageDraw, ImageFont

def conv(name, ttf, px):
    f = ImageFont.truetype(ttf, px)
    bitmap, glyphs = [], []
    for c in range(0x20, 0x7F):
        ch = chr(c)
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = x1 - x0, y1 - y0
        off = len(bitmap)
        if c == 0x20 or w <= 0 or h <= 0:
            glyphs.append((off, 0, 0, adv, 0, 0)); continue
        im = Image.new("1", (w, h), 0)
        d = ImageDraw.Draw(im); d.fontmode = "1"
        d.text((-x0, -y0), ch, font=f, anchor="ls", fill=1)
        px_ = im.load()
        # trim empty rows/columns left by the bbox
        rows = [y for y in range(h) if any(px_[x, y] for x in range(w))]
        cols = [x for x in range(w) if any(px_[x, y] for y in range(h))]
        if not rows:
            glyphs.append((off, 0, 0, adv, 0, 0)); continue
        ty0, ty1, tx0, tx1 = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
        acc = n = 0
        for y in range(ty0, ty1):
            for x in range(tx0, tx1):
                acc = (acc << 1) | (1 if px_[x, y] else 0); n += 1
                if n == 8: bitmap.append(acc); acc = n = 0
        if n: bitmap.append(acc << (8 - n))
        glyphs.append((off, tx1 - tx0, ty1 - ty0, adv, x0 + tx0, y0 + ty0))
    asc, desc = f.getmetrics()
    capTop = -glyphs[ord("H") - 0x20][5]
    out = [f"// {name}: Bai Jamjuree, {px} px, from {ttf.split('/')[-1]} (SIL Open Font License 1.1, Cadson Demak)"]
    out.append(f"const uint8_t {name}Bitmaps[] PROGMEM = {{")
    for k in range(0, len(bitmap), 16):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[k:k + 16]) + ",")
    out.append("};")
    out.append(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for c, g in zip(range(0x20, 0x7F), glyphs):
        out.append(f"  {{ {g[0]:5d}, {g[1]:3d}, {g[2]:3d}, {g[3]:3d}, {g[4]:4d}, {g[5]:4d} }},   // '{chr(c) if chr(c) not in '\\' else 'backslash'}'")
    out.append("};")
    out.append(f"const GFXfont {name} PROGMEM = {{ (uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, 0x20, 0x7E, {asc + desc} }};")
    out.append(f"#define {name.upper()}_CAP {capTop}   // height of a capital letter above the baseline")
    return "\n".join(out), len(bitmap)

hdr = ["// AUTO-GENERATED by ttf2gfx.py: Bai Jamjuree as Adafruit GFX fonts. Do not edit.",
       "#pragma once", "#include <Adafruit_GFX.h>", ""]
total = 0
for spec in sys.argv[2:]:
    name, ttf, px = spec.split(":")
    body, n = conv(name, ttf, int(px)); total += n
    hdr += [body, ""]
open(sys.argv[1], "w").write("\n".join(hdr))
print("wrote", sys.argv[1], total, "bitmap bytes")
